// Builds sw.js: precaches the app shell and small files, and caches everything else (the model, the runtime) the
// first time it is fetched, so a bin-station tablet keeps working without a network after one visit.
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import type { Plugin } from 'vite'

const RUNTIME_ONLY = /^(model\/encoder\.onnx|ort\/|assets\/.*\.wasm$)/ // large: cached only if fetched, never twice

function publicFiles(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? publicFiles(p, root) : [relative(root, p).split('\\').join('/')]
  })
}

const sw = (version: string, modelVersion: string, precache: string[]) => `// generated by sw-plugin.ts
const CACHE = 'cleanstream-${version}'
const MODEL_CACHE = 'cleanstream-model-${modelVersion}' // kept across app updates while the model is unchanged
const BIG = ${RUNTIME_ONLY.toString().replace('^(', '\\/(')}
const PRECACHE = ${JSON.stringify(precache)}
// The headers that let the model use several threads. GitHub Pages cannot set them, so the worker adds them.
const isolated = (res) => {
  if (!res || res.status === 0) return res
  const headers = new Headers(res.headers)
  headers.set('Cross-Origin-Opener-Policy', 'same-origin')
  headers.set('Cross-Origin-Embedder-Policy', 'require-corp')
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers })
}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE && k !== MODEL_CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return
  if (req.mode === 'navigate') {
    // fresh page when online, the cached one when not
    e.respondWith(fetch(req).catch(() => caches.match('./index.html', { ignoreSearch: true })).then(isolated))
    return
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(BIG.test(req.url) ? MODEL_CACHE : CACHE).then((c) => c.put(req, copy)) }
    return res
  })).then(isolated))
})
`

export function serviceWorker(publicDir: string): Plugin {
  return {
    name: 'cleanstream-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = [...Object.keys(bundle), ...publicFiles(publicDir)].filter((f) => !RUNTIME_ONLY.test(f) && f !== 'sw.js')
      const precache = ['./', ...files.map((f) => `./${f}`)]
      const hash = (parts: (string | Buffer)[]) => parts.reduce((h, p) => h.update(p), createHash('sha1')).digest('hex').slice(0, 10)
      const big = publicFiles(publicDir).filter((f) => RUNTIME_ONLY.test(f)).sort()
      const modelVersion = hash(big.map((f) => readFileSync(join(publicDir, f))))
      const version = hash([...precache, ...publicFiles(publicDir).filter((f) => !RUNTIME_ONLY.test(f)).map((f) => readFileSync(join(publicDir, f)))])
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: sw(version, modelVersion, precache) })
    },
  }
}
